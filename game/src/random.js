// Seeded random numbers (mulberry32) so the city, traffic and screenshot
// scenes are identical every time the same seed is used.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Small helpers built on a supplied rng function.
export function pick(rng, arr) { return arr[Math.floor(rng() * arr.length)]; }
export function range(rng, lo, hi) { return lo + rng() * (hi - lo); }
export function intRange(rng, lo, hi) { return lo + Math.floor(rng() * (hi - lo + 1)); }
export function chance(rng, p) { return rng() < p; }

// Deterministic hash of a string -> uint32, for seeding from a name.
export function hashString(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
